def test_fixture_freshness_statuses_are_styled_as_demonstration_not_as_fresh():
    script = (PUBLIC / "assets" / "app.js").read_text(encoding="utf-8")
    pills = script.split("var FRESHNESS_PILL", 1)[1].split("};", 1)[0]
