def test_every_observation_declares_a_recognised_origin(observations):
    for family, records in observations.items():
        for record in records:
            origin = record_origin(record)
            assert origin is not None, f"{family}: a record carries no evidence_origin"
            assert not provenance_problems(record, label=family)


def test_the_whole_observation_set_is_currently_fixture_backed(observations):
    """Stated as a test so the day a real source is enabled, this fails and
    forces every current-publication expectation below to be revisited."""
    origins = {record_origin(record) for records in observations.values() for record in records}
    assert origins <= FIXTURE_ORIGINS
    assert not any(
        qualifies_for_current_publication(record_origin(record))
        for records in observations.values()
        for record in records
    )


def test_no_fixture_is_attributed_to_a_real_publisher(observations):
    for family, records in observations.items():
        for record in records:
            if not is_fixture(record_origin(record)):
                continue
            assert record_source_id(record) == SYNTHETIC_SOURCE_ID, family
            assert record_intended_source_id(record), family


def test_no_fixture_carries_a_retrieval_timestamp(observations):
    for records in observations.values():
        for record in records:
            provenance = record["provenance"]
            assert provenance["retrieval_status"] == "not_retrieved"
            assert provenance["retrieved_at"] is None
            assert provenance["fixture_created_at"]


def test_every_intended_source_is_a_real_registry_entry(observations, registry):
    registry_ids = {source["id"] for source in registry["sources"]}
    for records in observations.values():
        for record in records:
            intended = record_intended_source_id(record)
            if intended:
                assert intended in registry_ids, intended


#: The corrected series-to-source map. WO-010 attributed the freight benchmark
#: and Brent to the fuel publisher, and FX and LSCI to the supply-chain index,
#: because the mapping lived in a hard-coded table beside the series names
#: rather than in each record's provenance.
EXPECTED_INTENDED_SOURCE = {
    "usd_thb_reference_rate": "BOT_FX",
    "thailand_lsci": "UNCTAD_MARITIME",
    "gscpi_index": "GSCPI",
    "brent_crude_price": "WB_COMMODITY",
    "thailand_diesel_retail_price": "EPPO_FUEL",
    "container_freight_benchmark": "FBX_PUBLIC",
    "thailand_port_calls": "IMF_PORTWATCH",
    "laem_chabang_container_throughput": "PAT_STATISTICS",
    "bangkok_port_container_throughput": "PAT_STATISTICS",
}

FORBIDDEN_MAPPINGS = {
    ("container_freight_benchmark", "EPPO_FUEL"),
    ("brent_crude_price", "EPPO_FUEL"),
    ("usd_thb_reference_rate", "GSCPI"),
    ("thailand_lsci", "GSCPI"),
    ("laem_chabang_container_throughput", "IMF_PORTWATCH"),
    ("bangkok_port_container_throughput", "IMF_PORTWATCH"),
}


@pytest.mark.parametrize("series_id,expected", sorted(EXPECTED_INTENDED_SOURCE.items()))
def test_each_series_stands_in_for_the_right_production_candidate(
    observations, series_id, expected
):
    records = [
        record
        for family in OBSERVATION_FAMILIES
        for record in observations[family]
        if (record.get("series_id") or record.get("indicator_id")) == series_id
    ]
    assert records, series_id
    assert {record_intended_source_id(record) for record in records} == {expected}


def test_trade_series_stand_in_for_thai_customs(observations):
    trade = observations["trade_observations"]
    assert trade
    assert {record_intended_source_id(record) for record in trade} == {"TH_CUSTOMS"}


@pytest.mark.parametrize("series_id,forbidden", sorted(FORBIDDEN_MAPPINGS))
def test_the_wo_010_mis_attributions_are_gone(observations, series_id, forbidden):
    """Each pair here is a mapping WO-010 actually made, or one the Work Order
    names as forbidden. Official TEU throughput in particular is not a
    PortWatch estimate and must not be attributed to one."""
    records = [
        record
        for family in OBSERVATION_FAMILIES
        for record in observations[family]
        if (record.get("series_id") or record.get("indicator_id")) == series_id
    ]
    assert records, series_id
    assert forbidden not in {record_intended_source_id(record) for record in records}


def test_effective_source_resolves_a_fixture_to_its_production_candidate(observations):
    record = observations["cost_observations"][0]
    assert record_source_id(record) == SYNTHETIC_SOURCE_ID
    assert effective_source_id(record) == record_intended_source_id(record)


def test_the_dashboard_derives_source_identity_from_provenance_not_a_lookup_table():
    """The hard-coded ``_SOURCE_BY_SERIES`` table is what let a series name and
    a publisher drift apart. It must not come back."""
    source = (ROOT / "scripts" / "build_dashboard.py").read_text(encoding="utf-8")
    assert "_SOURCE_BY_SERIES" not in source


