"""The fixture / current-publication boundary (WO-010-R1 §1, §6, §8, §9, §10).

WO-010 shipped a working analysis engine driven entirely by labelled fixtures.
Every number on the Dashboard was generated by this repository, and nothing in
the data model recorded that fact in a way the code could act on. These tests
pin the boundary that fixes it: a fixture may exercise the engine, and it may
never appear as current Logistics intelligence.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from analysis.provenance import (  # noqa: E402
    CURRENT_PUBLICATION,
    FIXTURE_ORIGINS,
    HISTORICAL_VALIDATION,
    LIVE_FRESHNESS_STATUSES,
    SYNTHETIC_SOURCE_ID,
    TECHNICAL_DEMO,
    effective_source_id,
    fixture_freshness_status,
    is_fixture,
    provenance_problems,
    qualifies_for_current_publication,
    record_intended_source_id,
    record_origin,
    record_source_id,
)
from scripts.build_dashboard import build_payloads  # noqa: E402
from scripts.validate import source_contract_checks  # noqa: E402

PUBLIC = ROOT / "dashboard" / "public"
OBSERVATION_FAMILIES = (
    "indicator_observations",
    "trade_observations",
    "port_observations",
    "cost_observations",
)


def _load(relative: str):
    return json.loads((ROOT / relative).read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def payloads():
    return build_payloads()


@pytest.fixture(scope="module")
def registry():
    return yaml.safe_load((ROOT / "config/sources.yaml").read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def observations():
    return {
        family: _load(f"data/observations/{family}.json")["records"]
        for family in OBSERVATION_FAMILIES
    }


