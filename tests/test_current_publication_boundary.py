def test_every_demonstration_heading_carries_its_own_marker():
    """A page-level banner is not enough: a reader who deep-links to a section
    or prints one panel must still see that it is a demonstration."""
    html = (PUBLIC / "index.html").read_text(encoding="utf-8")
    headings = re.findall(r'<h3 class="demo-heading">(.*?)</h3>', html, re.S)
    assert len(headings) >= 6
    for heading in headings:
        assert "pill-demo" in heading, heading


